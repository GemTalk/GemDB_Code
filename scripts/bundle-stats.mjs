#!/usr/bin/env node
//
// Assemble the GemDB Stats payload that ships inside the .vsix.
//
// GemDB Stats is GemTalk's statmon viewer, a Flutter app with a web build.
// GemDB Code shows that build in a webview (src/statistics.ts), so a statmon
// file can be charted wherever the editor is -- including code-server, where
// the only screen is a browser tab and a desktop app cannot appear.
//
// Like Grail and the MCP server, the payload is another repository's code,
// pinned in vendor-pins.sh. Unlike them it is not built here: compiling it
// needs the Flutter SDK, so GemDB Stats publishes the web build as a release
// asset, and this script downloads the pinned one and checks its SHA-256.
//
// Usage:
//   npm run bundle:stats                                   # the pinned release asset
//   STATS_WEB=/path/to/GemDB_Stats/app/build/web npm run bundle:stats   # a local build
//
// Environment:
//   STATS_WEB     a local `flutter build web` output to bundle instead of downloading
//   STATS_URL     a web-build .tar.gz to download instead of the pinned one
//   STATS_SHA256  its expected SHA-256; unchecked when STATS_URL is given without it
//   STATS_OUT     where to assemble the payload (default: stats/, which is what
//                 the .vsix ships; the unit tests point it elsewhere)
//
// What it checks and changes, and why HERE rather than when the panel opens:
// every one of these can fail, and a failure here is in front of whoever is
// packaging, while the same failure at run time is a blank panel on a user's
// screen. GemDB Stats' docs/embedding.md is the other side of this.
//
// - The build. It must load CanvasKit from its own files (the page's CSP
//   refuses Google's CDN), be dart2js only (the Wasm renderers are left out),
//   and start Flutter without a service worker (a webview runs its own).
// - The page. A webview needs a Content-Security-Policy, a <base href> that
//   points at the webview's resource URL, and a nonce on every script. The
//   build's index.html becomes `host.html`, a template whose three
//   `{{GEMDB_*}}` placeholders statistics.ts fills for each panel; everything
//   else on it, the loading screen included, is GemDB Stats' to design.
// - The files. The Wasm renderers, debug symbols, the service worker and the
//   PWA manifest never load in a webview: more than half of the build's 47 MB.

import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** What the hosted page loads. A build missing any of these is not one this can host. */
const REQUIRED = [
  'index.html',
  'flutter.js',
  'flutter_bootstrap.js',
  'main.dart.js',
  'version.json',
  'assets/AssetManifest.bin.json',
  'assets/FontManifest.json',
  // Flutter's loader picks the Chromium variant where the browser supports it
  // (VS Code's own window, Chrome, Edge) and the full one elsewhere (Firefox
  // or Safari pointed at code-server), so both stay.
  'canvaskit/canvaskit.js',
  'canvaskit/canvaskit.wasm',
  'canvaskit/chromium/canvaskit.js',
  'canvaskit/chromium/canvaskit.wasm',
];

/**
 * Paths, relative to the build, that never ship. Everything else does: GemDB
 * Stats decides what its build contains, and a list of what to KEEP would
 * silently drop the next asset it adds.
 */
function isLeftOut(relative) {
  const name = path.posix.basename(relative);
  return (
    name.endsWith('.symbols') ||
    // The Wasm renderers. Only a `--wasm` build loads them, and checkBuild
    // refuses one.
    /^canvaskit\/(skwasm|wimp)/.test(relative) ||
    // Loaded only when the build config sets `preferWebParagraph`, which
    // checkBuild refuses.
    relative.startsWith('canvaskit/webparagraph/') ||
    // host.html takes its place.
    relative === 'index.html' ||
    // Generated by every build, and registered by none that checkBuild accepts.
    relative === 'flutter_service_worker.js' ||
    // A PWA's install metadata. A webview cannot install anything.
    relative === 'manifest.json' ||
    relative.startsWith('icons/') ||
    relative === '.last_build_id'
  );
}

/**
 * Refuse a build a webview cannot run, judged from flutter_bootstrap.js: the
 * `_flutter.buildConfig` that `flutter build web` writes into it, and the
 * `_flutter.loader.load(...)` call after it.
 */
function checkBuild(bootstrap) {
  const match = /^_flutter\.buildConfig = (\{.*\});$/m.exec(bootstrap);
  if (!match) {
    throw new Error('flutter_bootstrap.js has no `_flutter.buildConfig = {...};` line.');
  }
  const config = JSON.parse(match[1]);
  // Without this the loader fetches CanvasKit from www.gstatic.com, which the
  // page's CSP refuses -- and which a server with no internet access could not
  // reach anyway.
  if (config.useLocalCanvasKit !== true) {
    throw new Error(
      'The build loads CanvasKit from a CDN. Build it with `--no-web-resources-cdn`.',
    );
  }
  if (config.canvasKitVariant !== undefined || config.preferWebParagraph !== undefined) {
    throw new Error(
      'The build chooses its own CanvasKit variant, which may need files this payload leaves out.',
    );
  }
  const builds = config.builds ?? [];
  if (!builds.some((b) => b.compileTarget === 'dart2js' && b.mainJsPath === 'main.dart.js')) {
    throw new Error('The build has no dart2js entry point at main.dart.js.');
  }
  // The loader prefers Wasm where the browser supports it, and its renderers
  // are left out of this payload, so a page that offered it would fail there.
  if (builds.some((b) => b.compileTarget === 'dart2wasm')) {
    throw new Error('The build includes a Wasm build. Build without `--wasm`.');
  }
  // Only the code after the config: the flutter.js inlined above it mentions
  // service workers in its own implementation.
  const start = bootstrap.slice(match.index + match[0].length);
  if (/serviceWorker/.test(start)) {
    throw new Error(
      'flutter_bootstrap.js registers a service worker, which a webview cannot host. ' +
        'GemDB Stats from PR #10 on starts Flutter without one.',
    );
  }
  return config;
}

/**
 * The policy the page runs under. `{{GEMDB_CSP_SOURCE}}` becomes the
 * webview's own resource origin, which serves both the build and the statmon
 * file, so nothing else is reachable.
 */
const CSP = [
  "default-src 'none'",
  // The bootstrap and what it loads come from the resource origin; the page's
  // own inline script carries the nonce. CanvasKit is WebAssembly, which a CSP
  // blocks unless 'wasm-unsafe-eval' allows it.
  "script-src 'nonce-{{GEMDB_NONCE}}' {{GEMDB_CSP_SOURCE}} 'wasm-unsafe-eval'",
  // Flutter writes its own <style> elements and style attributes.
  "style-src {{GEMDB_CSP_SOURCE}} 'unsafe-inline'",
  'img-src {{GEMDB_CSP_SOURCE}} data: blob:',
  'font-src {{GEMDB_CSP_SOURCE}} data: blob:',
  // Flutter fetches fonts, assets and CanvasKit's .wasm; the app fetches the
  // statmon file. All of them from the webview's resource origin.
  'connect-src {{GEMDB_CSP_SOURCE}}',
].join('; ');

/**
 * Replace exactly one match of `pattern` in `html`, or say which anchor the
 * build no longer has.
 */
function replaceOnce(html, pattern, replacement, what) {
  const matches = html.match(new RegExp(pattern.source, `${pattern.flags}g`)) ?? [];
  if (matches.length !== 1) {
    throw new Error(`index.html has ${matches.length} ${what}; GemDB Code needs exactly one.`);
  }
  return html.replace(pattern, replacement);
}

/** index.html, made into the template statistics.ts fills for each panel. */
function hostTemplate(indexHtml) {
  let html = indexHtml;
  html = replaceOnce(
    html,
    /<base\s+href="[^"]*"\s*\/?>/,
    '<base href="{{GEMDB_BASE}}">',
    '<base href> elements',
  );
  // Checked rather than changed: it is what starts the app.
  replaceOnce(
    html,
    /<script\b[^>]*\bsrc="flutter_bootstrap\.js"[^>]*>\s*<\/script>/,
    (tag) => tag,
    'flutter_bootstrap.js <script> tags',
  );
  html = html.replace(/<script(?![^>]*\bnonce=)(?=[\s>])/g, '<script nonce="{{GEMDB_NONCE}}"');
  // The PWA manifest is left out, and the CSP would refuse to fetch it.
  html = html.replace(/\s*<link\b[^>]*\brel="manifest"[^>]*>/g, '');
  // First in <head>, so the policy governs everything after it.
  html = replaceOnce(
    html,
    /<head\b[^>]*>/,
    (head) => `${head}\n  <meta http-equiv="Content-Security-Policy" content="${CSP}">`,
    '<head> elements',
  );
  return html;
}

function filesUnder(dir, prefix = '') {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    return entry.isDirectory() ? filesUnder(path.join(dir, entry.name), relative) : [relative];
  });
}

/** `PINNED_<name>` from vendor-pins.sh, which is shell and so read as text. */
function pin(name) {
  const pins = fs.readFileSync(path.join(REPO, 'vendor-pins.sh'), 'utf8');
  return new RegExp(`^PINNED_${name}=(.*)$`, 'm').exec(pins)?.[1].trim() ?? '';
}

/**
 * Download a web-build .tar.gz, check it, and unpack it into a fresh temporary
 * directory. Answers the build's folder: the archive's top level, or its one
 * folder.
 */
async function download(url, sha256, workdir) {
  console.log(`Downloading ${url}`);
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${url} answered ${response.status} ${response.statusText}.`);
  }
  const bytes = Buffer.from(await response.arrayBuffer());
  const actual = crypto.createHash('sha256').update(bytes).digest('hex');
  if (sha256 && actual !== sha256.toLowerCase()) {
    throw new Error(`${url} has SHA-256 ${actual}, not the pinned ${sha256}.`);
  }
  if (!sha256) console.log(`  unchecked: no SHA-256 given (it is ${actual})`);
  const archive = path.join(workdir, 'web.tar.gz');
  const unpacked = path.join(workdir, 'web');
  fs.writeFileSync(archive, bytes);
  fs.mkdirSync(unpacked);
  execFileSync('tar', ['-xzf', archive, '-C', unpacked]);
  if (fs.existsSync(path.join(unpacked, 'index.html'))) return unpacked;
  const entries = fs.readdirSync(unpacked, { withFileTypes: true });
  if (entries.length === 1 && entries[0].isDirectory()) {
    return path.join(unpacked, entries[0].name);
  }
  throw new Error(`${url} holds neither a web build nor one folder with a web build in it.`);
}

function assemble(web, dest) {
  const missing = REQUIRED.filter((file) => !fs.existsSync(path.join(web, file)));
  if (missing.length) {
    throw new Error(
      `${web} is not a complete GemDB Stats web build. Missing:\n` +
        missing.map((file) => `  ${file}`).join('\n'),
    );
  }

  const read = (file) => fs.readFileSync(path.join(web, file), 'utf8');
  const config = checkBuild(read('flutter_bootstrap.js'));
  const template = hostTemplate(read('index.html'));

  console.log(`Assembling ${dest} from ${web}`);
  fs.rmSync(dest, { recursive: true, force: true });
  let kept = 0;
  let bytes = 0;
  for (const relative of filesUnder(web)) {
    if (isLeftOut(relative)) continue;
    const to = path.join(dest, relative);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.copyFileSync(path.join(web, relative), to);
    kept += 1;
    bytes += fs.statSync(to).size;
  }
  fs.writeFileSync(path.join(dest, 'host.html'), template);
  return { config, version: JSON.parse(read('version.json')), kept, bytes };
}

async function main() {
  const dest = path.resolve(process.env.STATS_OUT ?? path.join(REPO, 'stats'));
  let web = process.env.STATS_WEB;
  let source = '';
  let workdir;
  try {
    if (!web) {
      const url = process.env.STATS_URL || pin('STATS_URL');
      const sha256 = process.env.STATS_URL ? process.env.STATS_SHA256 : pin('STATS_SHA256');
      if (!url) {
        throw new Error(
          'No GemDB Stats web build is pinned in vendor-pins.sh yet. ' +
            'Set STATS_WEB to a local build (GemDB_Stats/app/build/web).',
        );
      }
      if (!process.env.STATS_URL && !sha256) {
        throw new Error('vendor-pins.sh pins PINNED_STATS_URL without PINNED_STATS_SHA256.');
      }
      workdir = fs.mkdtempSync(path.join(os.tmpdir(), 'gemdb-stats-'));
      web = await download(url, sha256, workdir);
      source = url;
    }
    const { config, version, kept, bytes } = assemble(path.resolve(web), dest);

    // What was bundled, for whoever is reading a .vsix later. GemDB Code reads
    // nothing from it.
    fs.writeFileSync(
      path.join(dest, 'STATS_VERSION'),
      `stats=${version.version ?? 'unknown'}\n` +
        `engine=${config.engineRevision ?? 'unknown'}\n` +
        (source ? `source=${source}\n` : ''),
    );
    console.log(
      `Bundled GemDB Stats ${version.version ?? ''}: ${kept} files, ` +
        `${(bytes / 1024 / 1024).toFixed(1)} MB.`,
    );
  } finally {
    if (workdir) fs.rmSync(workdir, { recursive: true, force: true });
  }
}

try {
  await main();
} catch (error) {
  console.error(`ERROR: ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
}
